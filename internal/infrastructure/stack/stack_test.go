//go:noinline
func panicker() { panic("boom") }

func TestPanicFramesStartAtPanicSite(t *testing.T) {
	var pcs []uintptr
	func() {
		defer func() {
			_ = recover()
			pcs = capture()
		}()
		panicker()
	}()
	frames := New().Frames(pcs, true)
	newest := frames[len(frames)-1]
	if newest.Function != "stack.panicker" {
		t.Fatalf("newest frame should be the panicking function, got %+v", newest)
	}
	for _, f := range frames {
		if f.Function == "runtime.gopanic" || f.Function == "stack.capture" {
			t.Fatalf("recovery machinery not trimmed: %+v", f)
		}
	}
}

func TestFramesKeepsNewest100(t *testing.T) {
	var pcs []uintptr
	var rec func(int)
	rec = func(n int) {
		if n == 0 {
			p := make([]uintptr, 300)
			pcs = p[:runtime.Callers(1, p)]
			return
		}
		rec(n - 1)
	}
	rec(200)
	frames := New().Frames(pcs, false)
	if len(frames) != 100 {
		t.Fatalf("got %d frames", len(frames))
	}
	if !strings.Contains(frames[99].Function, "TestFramesKeepsNewest100.func1") {
		t.Fatalf("newest frame must be kept last: %+v", frames[99])
	}
}

// pkgErrorsFrame mimics github.com/pkg/errors.Frame (a uintptr) and StackTrace.
type pkgErrorsFrame uintptr
type pkgErrorsStack []pkgErrorsFrame
type pkgError struct{ stack pkgErrorsStack }

func (e *pkgError) Error() string              { return "pkg" }
func (e *pkgError) StackTrace() pkgErrorsStack { return e.stack }

type callersError struct{ pcs []uintptr }

func (e *callersError) Error() string      { return "callers" }
func (e *callersError) Callers() []uintptr { return e.pcs }

type badStackError struct{}

func (badStackError) Error() string        { return "bad" }
func (badStackError) StackTrace() []string { return []string{"x"} }

type panickyStack struct{}

func (panickyStack) Error() string         { return "p" }
func (panickyStack) StackTrace() []uintptr { panic("nope") }

func TestFromError(t *testing.T) {
	p := New()
	pcs := capture()
	stack := make(pkgErrorsStack, len(pcs))
	for i, pc := range pcs {
		stack[i] = pkgErrorsFrame(pc)
	}
	if got := p.FromError(&pkgError{stack: stack}); len(got) != len(pcs) || got[0] != pcs[0] {
		t.Fatalf("pkg/errors shape: %v", got)
	}
	if got := p.FromError(&callersError{pcs: pcs}); len(got) != len(pcs) {
		t.Fatal("Callers shape")
	}
	if p.FromError(errors.New("x")) != nil || p.FromError(badStackError{}) != nil || p.FromError(nil) != nil {
		t.Fatal("errors without a usable stack")
	}
	if p.FromError(panickyStack{}) != nil {
		t.Fatal("panicking StackTrace must be contained")
	}
	var nilPtr *pkgError
	if p.FromError(nilPtr) != nil {
		t.Fatal("typed nil")
	}
}
