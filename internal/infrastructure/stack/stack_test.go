type server struct{}

//go:noinline
func (s *server) handle() []uintptr { return capture() }

//go:noinline
func capture() []uintptr {
	pcs := make([]uintptr, 64)
	n := runtime.Callers(1, pcs)
	return pcs[:n]
}

//go:noinline
func outer() []uintptr { return (&server{}).handle() }

func TestFramesOrderAndNames(t *testing.T) {
	p := New()
	frames := p.Frames(outer(), false)
	if len(frames) < 4 {
		t.Fatalf("too few frames: %+v", frames)
	}
	newest := frames[len(frames)-1]
	if newest.Function != "stack.capture" || newest.Module != "github.com/getfaultline/faultline-go/internal/infrastructure/stack" {
		t.Fatalf("newest frame should be capture: %+v", newest)
	}
	prev := frames[len(frames)-2]
	if prev.Function != "stack.(*server).handle" {
		t.Fatalf("method name: %+v", prev)
	}
	if frames[len(frames)-3].Function != "stack.outer" {
		t.Fatalf("caller: %+v", frames[len(frames)-3])
	}
	if !newest.InApp || !strings.HasSuffix(newest.Filename, "stack_test.go") || newest.Lineno == 0 {
		t.Fatalf("in-app frame: %+v", newest)
	}
	// The oldest frames belong to the runtime/testing machinery (GOROOT): not in-app.
	if frames[0].InApp {
		t.Fatalf("oldest frame should be GOROOT: %+v", frames[0])
	}
}

func TestSplitFunction(t *testing.T) {
	cases := map[string][2]string{
		"main.(*Server).handle":                    {"main", "main.(*Server).handle"},
		"main.main.func1":                          {"main", "main.main.func1"},
		"github.com/a/b.(*T).m":                    {"github.com/a/b", "b.(*T).m"},
		"github.com/a/b.Generic[...]":              {"github.com/a/b", "b.Generic[...]"},
		"net/http.HandlerFunc.ServeHTTP":           {"net/http", "http.HandlerFunc.ServeHTTP"},
		"runtime.gopanic":                          {"runtime", "runtime.gopanic"},
		"weird":                                    {"", "weird"},
		"github.com/x/y.(*Hub).CaptureException.f": {"github.com/x/y", "y.(*Hub).CaptureException.f"},
	}
	for in, want := range cases {
		m, f := SplitFunction(in)
		if m != want[0] || f != want[1] {
			t.Errorf("%s: got (%s, %s)", in, m, f)
		}
	}
}

